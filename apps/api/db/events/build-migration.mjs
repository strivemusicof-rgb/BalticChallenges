// Generates db/migrations/015_events.sql from events.json.
// Usage: node db/events/build-migration.mjs
// Each event becomes a seasonal collection (with dates), one seasonal challenge per place, and a hidden badge.
// 015 is already applied on the server; later additions to events.json reach it through
// db/content/build-migration.mjs, which reuses the same (idempotent) SQL.
import { readFile, writeFile } from 'node:fs/promises';

import { eventSql } from './sql.mjs';

const here = new URL('./', import.meta.url);
const events = JSON.parse(await readFile(new URL('events.json', here), 'utf8'));

const lines = ['-- Seasonal events and national holidays (generated by db/events/build-migration.mjs).', '', ...eventSql(events)];

await writeFile(new URL('../migrations/015_events.sql', here), lines.join('\n'));
console.log(`wrote ${events.length} events`);
