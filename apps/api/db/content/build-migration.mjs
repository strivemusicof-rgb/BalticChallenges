// Generates db/migrations/017_latvia_content.sql: Latvian places from latvia.json (coordinates checked by
// scripts/resolve-latvia*.mjs into resolved.json), their challenges in EN/LV/RU, regional collections,
// new event places from db/events/events.json and the community goals.
// Usage: node db/content/build-migration.mjs
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';

import { eventSql, json, q } from '../events/sql.mjs';

const here = new URL('./', import.meta.url);
const places = JSON.parse(await readFile(new URL('latvia.json', here), 'utf8'));
const resolved = JSON.parse(await readFile(new URL('resolved.json', here), 'utf8'));
const events = JSON.parse(await readFile(new URL('../events/events.json', here), 'utf8'));
const photoDir = new URL('../../../../.photo-cache/latvia/', here);
const PHOTO_BASE = 'https://vps-1a18ee51.vps.ovh.net/uploads/places/';

// Safety metadata defaults per category: terrain, minutes, family, dogs, parking.
const META = {
  castles: ['Grass and gravel paths', 60, true, true, true],
  manors: ['Park paths', 60, true, true, true],
  churches: ['Paved', 30, true, false, true],
  fortresses: ['Uneven ground, ruins', 60, true, true, true],
  'old-towns': ['Cobblestones', 60, true, true, true],
  monuments: ['Paved', 20, true, true, true],
  museums: ['Indoor and paths', 90, true, false, true],
  architecture: ['Pavements', 30, true, true, true],
  viewpoints: ['Stairs or slope', 45, true, true, true],
  cities: ['Pavements', 60, true, true, true],
  food: ['Indoor, flat', 45, true, false, true],
  landscapes: ['Park paths', 45, true, true, true],
  bridges: ['Paved', 20, true, true, true],
  beaches: ['Sand', 60, true, true, true],
  piers: ['Concrete pier, uneven', 45, true, true, true],
  lighthouses: ['Paths, tower stairs', 45, true, true, true],
  'coastal-trails': ['Sand and forest paths', 60, true, true, true],
  'seaside-towns': ['Flat', 90, true, true, true],
  cliffs: ['Forest trail, steep edges', 90, true, true, true],
  caves: ['Forest paths, steps', 60, true, true, true],
  waterfalls: ['Riverside paths', 30, true, true, true],
  lakes: ['Shore paths', 60, true, true, true],
  rivers: ['Riverbank', 30, true, true, true],
  bogs: ['Boardwalk', 90, true, false, true],
  forests: ['Forest trails', 120, true, true, true],
  'nature-trails': ['Forest trails', 90, true, true, true],
  wildlife: ['Trails, keep distance from animals', 120, true, false, true],
  adventure: ['Slopes', 60, true, false, true],
  family: ['Station and train', 120, true, true, true],
};
const HISTORY = new Set(['castles', 'manors', 'churches', 'fortresses', 'old-towns', 'monuments', 'museums']);

const lines = [
  '-- Latvian content batch (generated by db/content/build-migration.mjs) and community goals for events.',
  '',
  '-- Community goals: one shared target per seasonal event, rewarded to everyone who took part.',
  'ALTER TABLE collections ADD COLUMN community_goal integer NOT NULL DEFAULT 0 CHECK (community_goal >= 0);',
  'ALTER TABLE collections ADD COLUMN community_xp integer NOT NULL DEFAULT 0 CHECK (community_xp >= 0);',
  'ALTER TABLE collections ADD COLUMN community_reached_at timestamptz;',
  'ALTER TABLE xp_events DROP CONSTRAINT xp_events_source_check;',
  `ALTER TABLE xp_events ADD CONSTRAINT xp_events_source_check
  CHECK (source IN ('challenge', 'achievement', 'collection', 'daily', 'weekly', 'monthly', 'goal', 'streak', 'admin', 'duel', 'community'));`,
  `CREATE INDEX IF NOT EXISTS challenge_attempts_completed_idx ON challenge_attempts (completed_at) WHERE status = 'completed';`,
  `INSERT INTO achievements (id, title, description, icon, rule, xp_reward, sort, i18n) VALUES
  ('together-1', 'Stronger Together', 'Help reach a community goal.', '', '{"type":"community_goals","count":1}', 150, 330,
   ${json({ lv: { title: 'Kopā stiprāki', description: 'Palīdzi sasniegt kopienas mērķi.' }, ru: { title: 'Вместе сильнее', description: 'Помогите достичь общей цели сообщества.' } })}),
  ('together-3', 'Heart of Latvia', 'Help reach three community goals.', '', '{"type":"community_goals","count":3}', 400, 331,
   ${json({ lv: { title: 'Latvijas sirds', description: 'Palīdzi sasniegt trīs kopienas mērķus.' }, ru: { title: 'Сердце Латвии', description: 'Помогите достичь трёх общих целей сообщества.' } })})
ON CONFLICT (id) DO NOTHING;`,
  '',
  '-- Places and their visit/discover challenges.',
];

let photos = 0;
for (const [slug, , category, region, city, , , radius, xp, difficulty, en, lv, ru] of places) {
  const r = resolved[slug];
  if (!r?.verified) throw new Error(`${slug} has no verified coordinates`);
  const [terrain, minutes, family, dog, parking] = META[category] ?? ['Paths', 45, true, true, true];
  const hasPhoto = r.credit && existsSync(new URL(`${slug}.jpg`, photoDir));
  if (hasPhoto) photos++;
  const images = hasPhoto ? `ARRAY[${q(`${PHOTO_BASE}${slug}.jpg`)}]` : `'{}'::text[]`;
  const placeI18n = { lv: { name: lv[0], description: lv[1] }, ru: { name: ru[0], description: ru[1] } };
  lines.push(
    `INSERT INTO places (slug, name, description, country, region_id, city, category_id, geog, radius_m, images, image_credit,
                    difficulty, terrain, est_duration_min, family_friendly, dog_friendly, parking, status, i18n)
SELECT ${q(slug)}, ${q(en[0])}, ${q(en[1])}, 'LV', r.id, ${q(city)}, ${q(category)},
       ST_SetSRID(ST_MakePoint(${r.lng.toFixed(6)}, ${r.lat.toFixed(6)}), 4326)::geography, ${radius}, ${images}, ${hasPhoto ? q(r.credit) : 'NULL'},
       ${q(difficulty)}::difficulty, ${q(terrain)}, ${minutes}, ${family}, ${dog}, ${parking}, 'published', ${json(placeI18n)}
FROM regions r WHERE r.country = 'LV' AND r.slug = ${q(region)}
ON CONFLICT (slug) DO NOTHING;`,
  );
  const discover = HISTORY.has(category);
  const challengeI18n = {
    lv: { title: lv[0], description: `${lv[1]} Pietuvojies ${radius} m attālumā, lai izpildītu.` },
    ru: { title: ru[0], description: `${ru[1]} Подойдите ближе чем на ${radius} м, чтобы выполнить.` },
  };
  lines.push(
    `INSERT INTO challenges (slug, title, description, type, category_id, place_id, country, region_id, difficulty, xp_reward, verification, status, i18n)
SELECT ${q(`visit-${slug}`)}, ${q(`${discover ? 'Discover' : 'Visit'} ${en[0]}`)}, ${q(`${en[1]} Get within ${radius} m to complete.`)},
       ${q(discover ? 'discover' : 'visit')}::challenge_type, p.category_id, p.id, p.country, p.region_id, p.difficulty, ${xp},
       ${q(discover ? 'gps_checkin' : 'gps')}::verification_type, 'published', ${json(challengeI18n)}
FROM places p WHERE p.slug = ${q(slug)}
ON CONFLICT (slug) DO NOTHING;`,
  );
}

const regions = [
  ['latvia-riga', 'riga', 'Rīga & Jūrmala', 'From Old Rīga to the Jūrmala pines.', 'Rīga un Jūrmala', 'No Vecrīgas līdz Jūrmalas priedēm.', 'Рига и Юрмала', 'От Старой Риги до юрмальских сосен.', 800, 20],
  ['latvia-vidzeme', 'vidzeme', 'Vidzeme', 'The Gauja valley, sandstone cliffs and the highest hills.', 'Vidzeme', 'Gaujas senleja, smilšakmens klintis un augstākie kalni.', 'Видземе', 'Долина Гауи, песчаниковые скалы и самые высокие холмы.', 1000, 21],
  ['latvia-kurzeme', 'kurzeme', 'Kurzeme', 'Wild coast, lighthouses and the waterfalls of Kuldīga.', 'Kurzeme', 'Mežonīgā jūrmala, bākas un Kuldīgas rumbas.', 'Курземе', 'Дикое побережье, маяки и водопады Кулдиги.', 1000, 22],
  ['latvia-zemgale', 'zemgale', 'Zemgale', 'Palaces, castles and the fairy-tale forests of Tērvete.', 'Zemgale', 'Pilis, muižas un Tērvetes pasaku meži.', 'Земгале', 'Дворцы, замки и сказочные леса Тервете.', 700, 23],
  ['latvia-latgale', 'latgale', 'Latgale', 'The land of blue lakes, basilicas and the Daugava bends.', 'Latgale', 'Zilo ezeru zeme, bazilikas un Daugavas loki.', 'Латгале', 'Край голубых озёр, базилик и излучин Даугавы.', 800, 24],
];
lines.push('', '-- Regional collections for Latvia.');
for (const [slug, region, enT, enD, lvT, lvD, ruT, ruD, xp, sort] of regions) {
  lines.push(
    `INSERT INTO collections (slug, title, description, icon, kind, country, xp_reward, status, sort, i18n)
VALUES (${q(slug)}, ${q(enT)}, ${q(enD)}, '', 'special', 'LV', ${xp}, 'published', ${sort},
        ${json({ lv: { title: lvT, description: lvD }, ru: { title: ruT, description: ruD } })})
ON CONFLICT (slug) DO NOTHING;
INSERT INTO collection_items (collection_id, challenge_id, position)
SELECT c.id, ch.id, row_number() OVER (ORDER BY ch.xp_reward DESC, ch.slug)
FROM collections c
JOIN regions r ON r.country = 'LV' AND r.slug = ${q(region)}
JOIN challenges ch ON ch.region_id = r.id AND ch.type IN ('visit', 'discover') AND ch.status = 'published'
WHERE c.slug = ${q(slug)}
ON CONFLICT DO NOTHING;`,
  );
}

// New places join the existing country and theme collections after their current items.
const themes = [
  ['discover-latvia', `ch.country = 'LV'`],
  ['baltic-castles', `ch.category_id = 'castles'`],
  ['baltic-coast', `ch.category_id IN (SELECT id FROM categories WHERE id = 'coast' OR parent_id = 'coast')`],
  ['baltic-manors', `ch.category_id = 'manors'`],
  ['sacred-places', `ch.category_id = 'churches'`],
  ['waterfalls-cliffs', `ch.category_id IN ('waterfalls', 'cliffs')`],
  ['baltic-lighthouses', `ch.category_id = 'lighthouses'`],
  ['baltic-viewpoints', `ch.category_id = 'viewpoints'`],
  ['wild-nature', `ch.category_id IN ('bogs', 'caves', 'cliffs', 'waterfalls', 'wildlife')`],
];
const newSlugs = places.map(([slug]) => q(`visit-${slug}`)).join(', ');
lines.push('', '-- Theme collections.');
for (const [slug, rule] of themes) {
  lines.push(
    `INSERT INTO collection_items (collection_id, challenge_id, position)
SELECT c.id, ch.id, (SELECT coalesce(max(position), 0) FROM collection_items WHERE collection_id = c.id) + row_number() OVER (ORDER BY ch.slug)
FROM collections c JOIN challenges ch ON ch.slug IN (${newSlugs}) AND ${rule}
WHERE c.slug = ${q(slug)}
ON CONFLICT DO NOTHING;`,
  );
}

lines.push('', '-- Events: new places and community goals (existing rows are left as they are).', ...eventSql(events, { goals: true }));
lines.push(
  `UPDATE collections SET community_goal = 300, community_xp = 150 WHERE slug = 'autumn-latvia-2026' AND community_goal = 0;`,
  '',
);

await writeFile(new URL('../migrations/017_latvia_content.sql', here), lines.join('\n'));
console.log(`wrote ${places.length} places (${photos} with photos), ${regions.length} regions, ${events.length} events`);
